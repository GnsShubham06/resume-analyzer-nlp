"""Prepare the 100-resume dataset (20 per category).

Steps (idempotent - safe to run again):
1. Content check of every SUPPLIED original resume in data/raw/<Category>/.
   Originals whose text clearly does not match their folder label are MOVED to
   data/excluded/<Category>/ (never relabelled) and listed in
   data/excluded/excluded_resumes.csv with the reason.
2. Each category is topped up to exactly 20 resumes with SYNTHETIC resumes of
   fictional people, generated reproducibly (fixed seed) from the hand-written
   content pools in scripts/synthetic_content.py and saved as PDF files named
   SYN_<CAT>_<nn>.pdf.  Every synthetic PDF is marked as synthetic in its file
   name, its PDF metadata and a visible footer line; the footer line is removed
   again during preprocessing so models cannot learn it.
3. Writes data/resume_sources.csv: one row per document with category,
   source type, provenance, licence and inclusion status.

Usage:  python scripts/prepare_dataset_100.py [--per_category 20] [--seed 2026]
"""
from __future__ import annotations

import argparse
import csv
import html
import random
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from src.config import CATEGORIES, DATA_DIR, RAW_DIR  # noqa: E402
from src.pdf_extraction import extract_text  # noqa: E402
from src.skill_extraction import content_label_check, extract_skills  # noqa: E402
from synthetic_content import (ADJACENT, CITIES, DOMAINS, FIRST_NAMES, GENERIC_BULLETS, LANGUAGES,  # noqa: E402
                               LAST_NAMES, SECTION_NAMES, SOFT_SKILLS, TRACKS, UNIVERSITIES, VOLUNTEER)

EXCLUDED_DIR = DATA_DIR / "excluded"
SOURCES_CSV = DATA_DIR / "resume_sources.csv"
SYN_STAMP = ("Synthetic resume - fictional person generated for the Resume Analyzer NLP student project; "
             "not a real individual.")
PREFIX = {"Engineering": "ENG", "HR": "HR", "Finance": "FIN", "Healthcare": "HLT", "Agriculture": "AGR"}
ORIGINAL_PROVENANCE = ("Supplied by the project team in Datasetnlp_1.zip (October 2026). The original public source "
                       "was not documented by the team and has not been verified.")
ORIGINAL_LICENCE = "Unknown - to be confirmed by the project team before any redistribution"
SYN_PROVENANCE = ("Generated by scripts/prepare_dataset_100.py (seed {seed}) from hand-written content pools in "
                  "scripts/synthetic_content.py; fictional person, employers and institutions")
SYN_LICENCE = "Created for this project; contains no third-party text"


# --------------------------------------------------------------------- step 1
def exclude_mismatched_originals() -> list[dict]:
    excluded = []
    for cat in CATEGORIES:
        for pdf in sorted((RAW_DIR / cat).glob("*")):
            if pdf.name.startswith("SYN_") or not pdf.is_file():
                continue
            text = extract_text(pdf)["text"]
            check = content_label_check(extract_skills(text), cat)
            if check["review_required"]:
                dest = EXCLUDED_DIR / cat
                dest.mkdir(parents=True, exist_ok=True)
                shutil.move(str(pdf), dest / pdf.name)
                excluded.append({"filename": pdf.name, "category_folder": cat, "reason": check["label_check"],
                                 "domain_scores": check["domain_scores"]})
    log = EXCLUDED_DIR / "excluded_resumes.csv"
    rows = []
    if log.exists():
        rows = list(csv.DictReader(log.open()))
    known = {r["filename"] for r in rows}
    rows += [{"filename": e["filename"], "category_folder": e["category_folder"], "reason": e["reason"],
              "domain_scores": str(e["domain_scores"])} for e in excluded if e["filename"] not in known]
    if rows:
        EXCLUDED_DIR.mkdir(parents=True, exist_ok=True)
        with log.open("w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["filename", "category_folder", "reason", "domain_scores"])
            w.writeheader()
            w.writerows(rows)
    return excluded


# --------------------------------------------------------------------- step 2
def _fill(template: str, rng: random.Random, **extra) -> str:
    big = rng.randint(35, 60)
    vals = dict(n=rng.randint(3, 40), pct=rng.randint(8, 35), big=big, small=rng.randint(15, big - 10),
                avail=rng.randint(91, 98), rate=rng.randint(55, 90), beds=rng.choice([24, 30, 40, 60]), acc=rng.randint(95, 99),
                money=rng.choice([f"INR {rng.randint(3, 90)} lakh", f"USD {rng.randint(20, 400)}K",
                                  f"INR {rng.randint(1, 9)}.{rng.randint(1, 9)} crore"]))
    vals.update(extra)
    return template.format(**vals)


def make_resume(cat: str, idx: int, seed: int) -> dict:
    rng = random.Random(f"{seed}-{cat}-{idx}")
    d = DOMAINS[cat]
    first, last = rng.choice(FIRST_NAMES), rng.choice(LAST_NAMES)
    years = rng.randint(2, 16)
    track = rng.choice(TRACKS[cat])                       # coherent career track
    title = rng.choice(track["titles"])
    focus = rng.choice(track["focus"])
    summary = _fill(rng.choice(d["summary"]), rng, title=title, years=years, focus=focus)
    on_track = [b for b in d["bullets"] if any(k in b.lower() for k in track["kw"])]
    off_track = [b for b in d["bullets"] if b not in on_track]

    # ---- jobs, newest first; durations add up to `years`
    n_jobs = 2 if years < 5 else rng.randint(2, 4)
    durations = [1 + rng.randint(0, 1) for _ in range(n_jobs - 1)]          # earlier / junior roles
    durations = [max(1, years - sum(durations))] + durations                 # current role gets the rest
    used, jobs, end_year = set(), [], 2025
    for j, dur in enumerate(durations):
        start_year = end_year - dur
        role_dom = cat
        if j == 0:
            role = title
        elif j == n_jobs - 1:
            role = rng.choice(d["junior"])
        else:
            role = rng.choice([t for t in track["titles"] if t != title] or d["titles"])
        k = rng.randint(5, 7) if j == 0 else rng.randint(3, 5)
        if j == n_jobs - 1 and n_jobs > 2 and rng.random() < 0.15:   # earlier career in a neighbouring field
            role_dom = ADJACENT[cat]
            role = rng.choice(DOMAINS[role_dom]["junior"])
            bullets = rng.sample(DOMAINS[role_dom]["bullets"], k)
        else:
            pool_on = [b for b in on_track if b not in used]
            pool_off = [b for b in off_track if b not in used]
            n_on = min(len(pool_on), max(1, round(k * 0.85)))
            bullets = rng.sample(pool_on, n_on) + rng.sample(pool_off, min(len(pool_off), k - n_on))
            rng.shuffle(bullets)
        used.update(bullets)
        if rng.random() < 0.25:
            bullets.append(rng.choice(GENERIC_BULLETS))
        months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
        start = f"{rng.choice(months)} {start_year}"
        end = "Present" if j == 0 else f"{rng.choice(months)} {end_year}"
        jobs.append({"role": role, "employer": rng.choice(DOMAINS[role_dom]["employers"]), "city": rng.choice(CITIES),
                     "dates": f"{start} - {end}", "bullets": [_fill(b, rng) for b in bullets]})
        end_year = start_year

    skills = rng.sample(d["skills"], rng.randint(8, 14)) + rng.sample(SOFT_SKILLS, rng.randint(2, 4))
    rng.shuffle(skills)
    degrees = rng.sample(d["degrees"], 2 if rng.random() < 0.4 else 1)
    grad = end_year - rng.randint(0, 1)
    education = [{"degree": deg, "school": rng.choice(UNIVERSITIES), "year": grad - 2 * i}
                 for i, deg in enumerate(sorted(degrees, key=lambda x: ("M" not in x[:3], x)))]
    return {
        "name": f"{first} {last}", "title": title, "city": rng.choice(CITIES),
        "email": f"{first.lower()}.{last.lower().replace(chr(39), '')}@example.com",
        "phone": f"+1 555-01{rng.randint(0, 99):02d}", "summary": summary, "jobs": jobs, "skills": skills,
        "education": education, "certs": rng.sample(d["certs"], rng.randint(0, 3)),
        "projects": [_fill(p, rng) for p in rng.sample(d["projects"], rng.randint(1, 2))] if rng.random() < 0.4 else [],
        "languages": rng.sample(LANGUAGES, rng.randint(2, 3)) if rng.random() < 0.5 else [],
        "volunteer": [rng.choice(VOLUNTEER)] if rng.random() < 0.25 else [],
        "order": rng.choice([["summary", "skills", "experience", "education", "certs", "projects", "languages", "volunteer"],
                             ["summary", "experience", "education", "skills", "certs", "projects", "volunteer", "languages"],
                             ["summary", "experience", "skills", "projects", "education", "certs", "languages", "volunteer"]]),
        "section_names": {k: rng.choice(v) for k, v in SECTION_NAMES.items()},
        "bullet_char": rng.choice(["•", "-", "–"]), "paragraph_jobs": rng.random() < 0.15,
        "skills_sep": rng.choice([", ", " | ", " · "]), "font": rng.choice(["Helvetica", "Times-Roman"]),
        "upper_headings": rng.random() < 0.5,
    }


def render_pdf(r: dict, path: Path, category: str):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    f = r["font"]
    fb = "Helvetica-Bold" if f == "Helvetica" else "Times-Bold"
    e = html.escape
    name_s = ParagraphStyle("n", fontName=fb, fontSize=17, leading=21)
    sub_s = ParagraphStyle("s", fontName=f, fontSize=10.5, leading=14, textColor=colors.HexColor("#333333"))
    h_s = ParagraphStyle("h", fontName=fb, fontSize=11.5, leading=15, spaceBefore=8, spaceAfter=3,
                         textColor=colors.HexColor("#1f3b57"))
    b_s = ParagraphStyle("b", fontName=f, fontSize=10, leading=13.5)
    li_s = ParagraphStyle("li", parent=b_s, leftIndent=10)
    story = [Paragraph(e(r["name"]), name_s), Paragraph(e(r["title"]), sub_s),
             Paragraph(e(f"{r['city']}  |  {r['email']}  |  {r['phone']}"), sub_s), Spacer(1, 4)]
    head = lambda k: Paragraph(e(r["section_names"][k].upper() if r["upper_headings"] else r["section_names"][k]), h_s)  # noqa: E731
    for sec in r["order"]:
        if sec == "summary":
            story += [head(sec), Paragraph(e(r["summary"]), b_s)]
        elif sec == "skills":
            story += [head(sec), Paragraph(e(r["skills_sep"].join(r["skills"])), b_s)]
        elif sec == "experience":
            story.append(head(sec))
            for j in r["jobs"]:
                story.append(Paragraph(f"<b>{e(j['role'])}</b>, {e(j['employer'])}, {e(j['city'])}", b_s))
                story.append(Paragraph(f"<i>{e(j['dates'])}</i>", b_s))
                if r["paragraph_jobs"]:
                    story.append(Paragraph(e(" ".join(j["bullets"])), b_s))
                else:
                    story += [Paragraph(f"{r['bullet_char']} {e(b)}", li_s) for b in j["bullets"]]
                story.append(Spacer(1, 4))
        elif sec == "education":
            story.append(head(sec))
            story += [Paragraph(e(f"{x['degree']}, {x['school']}, {x['year']}"), b_s) for x in r["education"]]
        elif sec in ("certs", "projects", "languages", "volunteer") and r[sec]:
            story.append(head(sec))
            if sec == "languages":
                story.append(Paragraph(e(", ".join(r[sec])), b_s))
            else:
                story += [Paragraph(f"{r['bullet_char']} {e(x)}", li_s) for x in r[sec]]

    def stamp(canvas, doc):
        canvas.saveState()
        canvas.setFont(f, 7.5)
        canvas.setFillColor(colors.HexColor("#888888"))
        canvas.drawString(18 * mm, 9 * mm, SYN_STAMP)
        canvas.restoreState()

    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title=f"SYNTHETIC resume ({category})",
                            subject="SYNTHETIC - fictional person, generated for the Resume Analyzer NLP project",
                            keywords="synthetic, fictional, resume-analyzer-nlp", author="Resume Analyzer NLP project")
    doc.build(story, onFirstPage=stamp, onLaterPages=stamp)


def top_up(per_category: int, seed: int) -> dict:
    made = {}
    for cat in CATEGORIES:
        folder = RAW_DIR / cat
        files = [p for p in folder.glob("*") if p.is_file()]
        idx = 1
        made[cat] = 0
        while len(files) < per_category:
            path = folder / f"SYN_{PREFIX[cat]}_{idx:02d}.pdf"
            if not path.exists():
                render_pdf(make_resume(cat, idx, seed), path, cat)
                files.append(path)
                made[cat] += 1
            idx += 1
    return made


# --------------------------------------------------------------------- step 3
def write_sources(seed: int):
    rows = []
    for cat in CATEGORIES:
        for p in sorted((RAW_DIR / cat).glob("*")):
            syn = p.name.startswith("SYN_")
            rows.append({"filename": p.name, "category": cat, "path": str(p.relative_to(ROOT)),
                         "source_type": "synthetic" if syn else "supplied_original", "status": "included",
                         "provenance": SYN_PROVENANCE.format(seed=seed) if syn else ORIGINAL_PROVENANCE,
                         "licence": SYN_LICENCE if syn else ORIGINAL_LICENCE,
                         "notes": "fictional identity; contact details use example.com / 555-01xx" if syn else ""})
        for p in sorted((EXCLUDED_DIR / cat).glob("*.pdf")) if (EXCLUDED_DIR / cat).exists() else []:
            rows.append({"filename": p.name, "category": cat, "path": str(p.relative_to(ROOT)),
                         "source_type": "supplied_original", "status": "excluded_label_mismatch",
                         "provenance": ORIGINAL_PROVENANCE, "licence": ORIGINAL_LICENCE,
                         "notes": "content does not match folder label; see data/excluded/excluded_resumes.csv"})
    with SOURCES_CSV.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per_category", type=int, default=20)
    ap.add_argument("--seed", type=int, default=2026)
    a = ap.parse_args()
    excl = exclude_mismatched_originals()
    print(f"moved {len(excl)} label-mismatched originals to data/excluded/:",
          [(x['filename'], x['category_folder'], x['reason']) for x in excl])
    made = top_up(a.per_category, a.seed)
    print("synthetic resumes created per category:", made)
    rows = write_sources(a.seed)
    inc = [r for r in rows if r["status"] == "included"]
    for cat in CATEGORIES:
        c = [r for r in inc if r["category"] == cat]
        print(f"  {cat:12s} {len(c):3d} included ({sum(r['source_type'] == 'synthetic' for r in c)} synthetic)")
    print("total included:", len(inc), "-> data/resume_sources.csv")


if __name__ == "__main__":
    main()
